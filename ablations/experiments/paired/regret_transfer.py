"""
Regret Transfer Experiment — Cross-Adversary Probe Evaluation.

Tests whether protagonist representations generalize across different
adversary conditions by measuring probe transfer between level subsets.

Primary mode (cross-adversary): Uses adversary-generated levels from
different PAIRED training runs. Two variants:
  (a) Cross-seed: levels from adversary trained with seed A vs seed B
  (b) Cross-stage: levels from the same adversary at different training
      steps (e.g., early vs late checkpoint from the same run)
Both variants use the same secondary_checkpoint_path mechanism — the
difference is only which checkpoint is passed.

Fallback mode (wall-density proxy): When no secondary checkpoint is
provided, splits random levels by wall density as a proxy.

Protocol (cross-adversary):
1. Generate levels using PRIMARY adversary (from main checkpoint)
2. Generate levels using SECONDARY adversary (from secondary checkpoint)
3. Run PRIMARY protagonist on both sets, collecting h-states
4. Compute regret via antagonist rollouts
5. Train probes on subset A (primary adversary levels), test on subset B (secondary)
6. Generalization gap = R²_in - R²_out
"""

from typing import Dict, List, Optional, Any
import os
import numpy as np
import jax
import jax.numpy as jnp
import chex
import logging

from ..base import CheckpointExperiment
from ..utils.paired_helpers import (
    generate_levels,
    generate_constrained_levels,
    generate_adversary_levels,
    extract_level_features_batch,
    get_pro_ant_returns,
    get_pro_hstates,
    compute_difficulty,
)
from ..probes.property_probe import (
    train_probe,
    compute_probe_comparison,
)

logger = logging.getLogger(__name__)


class RegretTransferExperiment(CheckpointExperiment):
    """
    Cross-adversary probe evaluation for representation generalization.

    Primary mode: Train probes on protagonist h-states from levels generated
    by one adversary, test on h-states from levels generated by a different
    adversary. The generalization gap measures whether representations are
    specific to particular adversary strategies.

    Two sub-variants (both use secondary_checkpoint_path):
      - Cross-seed: secondary checkpoint from a different PAIRED training run
      - Cross-stage: secondary checkpoint from the same run at a different step
        (e.g., checkpoint_5000 vs checkpoint_25000)

    Fallback mode: Split random levels by wall density when no secondary
    checkpoint is available.
    """

    @property
    def name(self) -> str:
        return "regret_transfer"

    def __init__(
        self,
        secondary_train_state=None,
        secondary_agent=None,
        secondary_checkpoint_path: str = None,
        **kwargs,
    ):
        # Pop primary checkpoint path from kwargs if present (set by run_experiment)
        self._primary_checkpoint_path = kwargs.pop('checkpoint_path', None)
        super().__init__(**kwargs)
        self.n_levels_per_subset = self.exp_config("n_levels_per_subset")
        self.max_steps = self.exp_config("max_steps", 256)
        self.secondary_train_state = secondary_train_state
        self.secondary_agent = secondary_agent
        self._secondary_checkpoint_path = secondary_checkpoint_path

        self._data: Optional[Dict[str, Any]] = None
        self._results: Dict[str, Any] = {}

    def _detect_cross_adversary_variant(self) -> str:
        """Detect whether this is cross-seed or cross-stage based on checkpoint paths.

        Cross-stage: both checkpoints share the same seed directory
        (e.g., agent/seed_0/checkpoint_5000 vs agent/seed_0/checkpoint_25000).
        Cross-seed: different seed directories or different agent directories.
        """
        primary = self._primary_checkpoint_path
        secondary = self._secondary_checkpoint_path
        if not primary or not secondary:
            return 'cross_adversary'  # generic label

        # Compare parent directories (seed_X level)
        primary_parent = os.path.dirname(os.path.normpath(primary))
        secondary_parent = os.path.dirname(os.path.normpath(secondary))
        if primary_parent == secondary_parent:
            return 'cross_stage'
        return 'cross_seed'

    def collect_data(self, rng: chex.PRNGKey) -> Dict[str, Any]:
        """Dispatch to cross-adversary or wall-density proxy mode."""
        if self.training_method != "paired":
            self._data = {'error': f'Requires PAIRED, got {self.training_method}'}
            return self._data

        if self.secondary_train_state is not None:
            return self._collect_cross_adversary(rng)
        else:
            logger.warning(
                "No secondary_train_state provided; using wall-density proxy. "
                "For PDF-faithful cross-adversary evaluation, pass "
                "secondary_checkpoint_path in experiment_kwargs."
            )
            return self._collect_wall_density_proxy(rng)

    def _collect_cross_adversary(self, rng: chex.PRNGKey) -> Dict[str, Any]:
        """PDF-faithful path: adversary-generated levels from different seeds."""
        n = self.n_levels_per_subset

        # --- Subset A: levels from PRIMARY adversary ---
        rng, rng_a = jax.random.split(rng)
        adv_ts_primary = getattr(self.train_state, 'adv_train_state', None)
        if adv_ts_primary is None:
            self._data = {'error': 'Primary train_state has no adv_train_state'}
            return self._data

        levels_a = generate_adversary_levels(
            self.agent, adv_ts_primary, rng_a, n,
        )

        # --- Subset B: levels from SECONDARY adversary ---
        rng, rng_b = jax.random.split(rng)
        sec_agent = self.secondary_agent or self.agent
        adv_ts_secondary = getattr(self.secondary_train_state, 'adv_train_state', None)
        if adv_ts_secondary is None:
            self._data = {'error': 'Secondary train_state has no adv_train_state'}
            return self._data

        levels_b = generate_adversary_levels(
            sec_agent, adv_ts_secondary, rng_b, n,
        )

        # Extract features
        features_a = extract_level_features_batch(levels_a)
        features_b = extract_level_features_batch(levels_b)

        # Get protagonist h-states on both subsets (always use PRIMARY protagonist)
        rng, ha_rng, hb_rng = jax.random.split(rng, 3)
        hstates_a = get_pro_hstates(ha_rng, levels_a, self, self.max_steps)
        hstates_b = get_pro_hstates(hb_rng, levels_b, self, self.max_steps)

        # Get returns and regret for both subsets (primary protagonist + antagonist)
        rng, eval_a_rng, eval_b_rng = jax.random.split(rng, 3)
        pro_ret_a, ant_ret_a, regrets_a = get_pro_ant_returns(eval_a_rng, levels_a, self, self.max_steps)
        pro_ret_b, ant_ret_b, regrets_b = get_pro_ant_returns(eval_b_rng, levels_b, self, self.max_steps)

        # Get difficulties
        rng, diff_a_rng, diff_b_rng = jax.random.split(rng, 3)
        diff_a = compute_difficulty(levels_a, self, diff_a_rng, self.max_steps)
        diff_b = compute_difficulty(levels_b, self, diff_b_rng, self.max_steps)

        self._data = {
            'subset_a': {
                'hstates': hstates_a,
                'wall_density': np.array(features_a['wall_density']),
                'goal_distance': np.array(features_a['goal_distance']),
                'pro_returns': pro_ret_a,
                'ant_returns': ant_ret_a,
                'regrets': regrets_a,
                'difficulties': np.array(diff_a),
                'label': 'primary_adversary',
            },
            'subset_b': {
                'hstates': hstates_b,
                'wall_density': np.array(features_b['wall_density']),
                'goal_distance': np.array(features_b['goal_distance']),
                'pro_returns': pro_ret_b,
                'ant_returns': ant_ret_b,
                'regrets': regrets_b,
                'difficulties': np.array(diff_b),
                'label': 'secondary_adversary',
            },
            'n_per_subset': n,
            'mode': 'cross_adversary',
            'variant': self._detect_cross_adversary_variant(),
        }
        return self._data

    def _collect_wall_density_proxy(self, rng: chex.PRNGKey) -> Dict[str, Any]:
        """Fallback path: split random levels by wall density."""
        n = self.n_levels_per_subset

        # --- Subset A: high wall density (harder) ---
        rng, gen_a_rng = jax.random.split(rng)
        levels_a = generate_constrained_levels(
            self.agent, gen_a_rng, n,
            constraints={'wall_density': (0.25, 0.5)},
        )

        # --- Subset B: low wall density (easier) ---
        rng, gen_b_rng = jax.random.split(rng)
        levels_b = generate_constrained_levels(
            self.agent, gen_b_rng, n,
            constraints={'wall_density': (0.0, 0.15)},
        )

        # Extract features
        features_a = extract_level_features_batch(levels_a)
        features_b = extract_level_features_batch(levels_b)

        # Get protagonist h-states on both subsets
        rng, ha_rng, hb_rng = jax.random.split(rng, 3)
        hstates_a = get_pro_hstates(ha_rng, levels_a, self, self.max_steps)
        hstates_b = get_pro_hstates(hb_rng, levels_b, self, self.max_steps)

        # Get returns and regret for both subsets
        rng, eval_a_rng, eval_b_rng = jax.random.split(rng, 3)
        pro_ret_a, ant_ret_a, regrets_a = get_pro_ant_returns(eval_a_rng, levels_a, self, self.max_steps)
        pro_ret_b, ant_ret_b, regrets_b = get_pro_ant_returns(eval_b_rng, levels_b, self, self.max_steps)

        # Get difficulties
        rng, diff_a_rng, diff_b_rng = jax.random.split(rng, 3)
        diff_a = compute_difficulty(levels_a, self, diff_a_rng, self.max_steps)
        diff_b = compute_difficulty(levels_b, self, diff_b_rng, self.max_steps)

        self._data = {
            'subset_a': {
                'hstates': hstates_a,
                'wall_density': np.array(features_a['wall_density']),
                'goal_distance': np.array(features_a['goal_distance']),
                'pro_returns': pro_ret_a,
                'ant_returns': ant_ret_a,
                'regrets': regrets_a,
                'difficulties': np.array(diff_a),
                'label': 'high_wall_density',
            },
            'subset_b': {
                'hstates': hstates_b,
                'wall_density': np.array(features_b['wall_density']),
                'goal_distance': np.array(features_b['goal_distance']),
                'pro_returns': pro_ret_b,
                'ant_returns': ant_ret_b,
                'regrets': regrets_b,
                'difficulties': np.array(diff_b),
                'label': 'low_wall_density',
            },
            'n_per_subset': n,
            'mode': 'wall_density_proxy',
        }
        return self._data

    def analyze(self) -> Dict[str, Any]:
        """Train probes on subset A, test on subset B, measure generalization gap."""
        if self._data is None or 'error' in self._data:
            self._results = self._data or {'error': 'No data'}
            return self._results

        a = self._data['subset_a']
        b = self._data['subset_b']

        is_proxy = self._data.get('mode') == 'wall_density_proxy'
        results = {
            'training_method': self.training_method,
            'mode': self._data.get('mode', 'unknown'),
            'is_proxy': is_proxy,
            'note': 'Wall-density proxy — not directly comparable to cross-adversary evaluation' if is_proxy else None,
        }

        # --- Probe features to test ---
        probe_targets = {
            'wall_density': ('wall_density', 'regression'),
            'goal_distance': ('goal_distance', 'regression'),
            'regret': ('regrets', 'regression'),
            'difficulty': ('difficulties', 'regression'),
            'pro_return': ('pro_returns', 'regression'),
        }

        generalization_gaps = {}
        per_feature = {}

        for feat_name, (key, task) in probe_targets.items():
            targets_a = a[key]
            targets_b = b[key]

            # Train on A (in-distribution)
            probe_a, metrics_a = train_probe(
                a['hstates'], targets_a,
                probe_type="linear", task=task,
            )
            r2_in = metrics_a.get('mean_score', 0.0)

            # Test on B (out-of-distribution)
            preds_b = probe_a.predict(b['hstates'])
            from sklearn.metrics import r2_score
            try:
                r2_out = float(r2_score(targets_b, preds_b))
            except ValueError:
                r2_out = 0.0

            # Also train on B and test on A (bidirectional)
            probe_b, metrics_b = train_probe(
                b['hstates'], targets_b,
                probe_type="linear", task=task,
            )
            r2_in_b = metrics_b.get('mean_score', 0.0)

            preds_a = probe_b.predict(a['hstates'])
            try:
                r2_out_b = float(r2_score(targets_a, preds_a))
            except ValueError:
                r2_out_b = 0.0

            gap_a_to_b = float(r2_in - r2_out)
            gap_b_to_a = float(r2_in_b - r2_out_b)
            mean_gap = float((gap_a_to_b + gap_b_to_a) / 2)

            generalization_gaps[feat_name] = mean_gap

            per_feature[feat_name] = {
                'r2_train_A_test_A': float(r2_in),
                'r2_train_A_test_B': float(r2_out),
                'gap_A_to_B': gap_a_to_b,
                'r2_train_B_test_B': float(r2_in_b),
                'r2_train_B_test_A': float(r2_out_b),
                'gap_B_to_A': gap_b_to_a,
                'mean_gap': mean_gap,
                'generalizes': mean_gap < 0.1,
            }

        results['generalization_gaps'] = generalization_gaps
        results['per_feature'] = per_feature

        # --- Summary ---
        all_gaps = list(generalization_gaps.values())
        results['summary'] = {
            'mean_generalization_gap': float(np.mean(all_gaps)),
            'max_generalization_gap': float(np.max(all_gaps)),
            'n_generalizing_features': sum(1 for g in all_gaps if g < 0.1),
            'n_total_features': len(all_gaps),
            'representations_generalize': float(np.mean(all_gaps)) < 0.1,
        }

        # --- Subset statistics ---
        results['subset_stats'] = {
            'subset_A': {
                'label': a['label'],
                'mean_wall_density': float(np.mean(a['wall_density'])),
                'mean_regret': float(np.mean(a['regrets'])),
                'mean_pro_return': float(np.mean(a['pro_returns'])),
            },
            'subset_B': {
                'label': b['label'],
                'mean_wall_density': float(np.mean(b['wall_density'])),
                'mean_regret': float(np.mean(b['regrets'])),
                'mean_pro_return': float(np.mean(b['pro_returns'])),
            },
        }

        self._results = results
        return results

    def visualize(self) -> Dict[str, Any]:
        """Visualize generalization gaps."""
        import matplotlib.pyplot as plt
        import matplotlib
        matplotlib.use('Agg')

        figures = {}

        if not self._results or 'error' in self._results:
            return figures

        try:
            per_feature = self._results.get('per_feature', {})
            feat_names = list(per_feature.keys())
            mode = self._results.get('mode', 'unknown')

            if not feat_names:
                return figures

            fig, axes = plt.subplots(1, 2, figsize=(14, 5))

            # In-distribution vs out-of-distribution R²
            ax = axes[0]
            x = np.arange(len(feat_names))
            width = 0.35
            r2_in = [per_feature[f]['r2_train_A_test_A'] for f in feat_names]
            r2_out = [per_feature[f]['r2_train_A_test_B'] for f in feat_names]
            ax.bar(x - width / 2, r2_in, width, label='In-distribution (A→A)', alpha=0.8)
            ax.bar(x + width / 2, r2_out, width, label='Out-of-distribution (A→B)', alpha=0.8)
            ax.set_xticks(x)
            ax.set_xticklabels(feat_names, rotation=45, ha='right')
            ax.set_ylabel('Probe R²')
            mode_label = "Cross-Adversary" if mode == "cross_adversary" else "Wall-Density Proxy"
            ax.set_title(f'Regret Transfer: Probe Generalization ({mode_label})')
            ax.legend()
            ax.grid(True, alpha=0.3, axis='y')

            # Generalization gap bar chart
            ax = axes[1]
            gaps = [per_feature[f]['mean_gap'] for f in feat_names]
            colors = ['green' if g < 0.1 else 'red' for g in gaps]
            ax.bar(x, gaps, color=colors, alpha=0.8)
            ax.set_xticks(x)
            ax.set_xticklabels(feat_names, rotation=45, ha='right')
            ax.set_ylabel('Generalization Gap (R²_in - R²_out)')
            ax.set_title('Generalization Gap by Feature')
            ax.axhline(y=0.1, color='k', linestyle='--', alpha=0.5, label='Threshold')
            ax.legend()
            ax.grid(True, alpha=0.3, axis='y')

            plt.tight_layout()
            fig.canvas.draw()
            buf = fig.canvas.buffer_rgba()
            figures["regret_transfer"] = np.asarray(buf)[:, :, :3]
            plt.close(fig)
        except Exception:
            pass

        return figures
